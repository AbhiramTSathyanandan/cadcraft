#!/usr/bin/env bash
# Assemble docs/assistant-reference.md (hand-written head + generated catalogue) and mirror it
# into the Craneye API as a TypeScript string the Lambda bundles (esbuild has no .md loader).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/docs/assistant-reference.md"
{ cat "$ROOT/docs/assistant-reference-head.md"; python3 "$ROOT/tools/command-reference/generate.py"; } > "$OUT"
API_DIR="${CRANEYE_API_DIR:-$ROOT/../backend/.worktrees/cad-assist/apps/api}"
if [[ -d "$API_DIR" ]]; then
  cp "$OUT" "$API_DIR/src/lib/lift-plan-v2/cadcraft-reference.md"
  { echo "// GENERATED by cadcraft/tools/command-reference/build.sh — do not edit; edit docs/assistant-reference-head.md or the engine's CommandSpecs."
    echo "/* eslint-disable */"
    printf 'export const CADCRAFT_REFERENCE = '
    python3 -c 'import json,sys; print(json.dumps(open(sys.argv[1], encoding="utf-8").read()) + ";")' "$OUT"
  } > "$API_DIR/src/lib/lift-plan-v2/cadcraft-reference.ts"
  echo "wrote $API_DIR/src/lib/lift-plan-v2/cadcraft-reference.{md,ts}"
fi
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
